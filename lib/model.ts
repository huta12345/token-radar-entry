// Token Radar model v2 ("radar-2-comps"): comparables-based implied value.
//
// Every input comes from the sealed snapshot only. No protocol name is
// special-cased; the same function scores every row.
//
// Formula (all in USD unless noted):
//   catMultiple = median(mcap_usd / tvl_usd) over token-bearing protocols in
//                 the SAME category, using only categories with >= 3
//                 comparables; otherwise the global median (0.205).
//                 Clamped to [0.05, 0.80] so one outlier category (a single
//                 protocol at 400x, or a 12x collateral manager) cannot
//                 dominate the board. Medians, not means, for the same reason.
//                 Protocols whose token records mcap_usd 0 (15 in this
//                 snapshot) are excluded: a $0 cap is not a market price.
//   growthMult  = 1 + clamp(change_7d, -60, 120) / 100 * 0.35
//                 (7-day TVL change is noisy, so it is dampened: weight 0.35,
//                 not 0.5; a +120% week moves value by +42%, a -60% week by -21%.)
//   maturityMult= 0.65 + 0.35 * ln(1 + min(age_days, 1460)) / ln(1461)
//                 (log-age: survival with no token yet is evidence the
//                 protocol is real, but the gain flattens — a 4-year-old
//                 protocol is not twice as proven as a 2-year-old one.
//                 Unknown listed_at uses 365 days.)
//   chainMult   = 1 + 0.03 * min(max(chains - 1, 0), 3)   (max 1.09)
//                 (each extra chain is reach, capped: the 14th chain adds
//                 nothing a farmer can use.)
//   implied     = round(TVL * catMultiple * 0.85 * growthMult
//                       * maturityMult * chainMult), min $1
//   0.85 is a uniform pre-token launch discount: a token that does not
//   trade yet launches below seasoned comps (no float, no liquidity,
//   no price history). It is applied to every row alike, so it never
//   changes the ranking on its own — it only keeps the level honest.
//
// Why this beats a flat TVL multiple: a flat 0.25x says a lending
// protocol and a DEX are worth the same per TVL dollar. The market
// disagrees — in this snapshot, token-bearing DEXes trade at a median
// 0.342x TVL while token-bearing lenders trade at 0.132x, bridges at
// 0.557x and RWA at 0.275x. Using the category's own multiple lets the
// board rank a $200M RWA protocol above a $300M lender when the market
// would, and stops a single-category bubble (Risk Curators: only one
// token-bearing comp, at 2.975x) from crowning the whole board.
//
// Board: all 40 watchlist slugs, plus the 160 largest-TVL pre-token
// protocols below the $50M floor (the early radar). Live-token protocols
// are set aside with their market caps shown, never ranked as pre-token.

