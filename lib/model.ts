const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

function median(values: number[]): number {
  const s = [...values].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 === 1 ? s[mid]! : (s[mid - 1]! + s[mid]!) / 2;
}

/**
 * Category comparables: for each category with at least
 * `min_comparables` token-bearing protocols, the median mcap/TVL,
 * clamped to [min_multiple, max_multiple]. Categories with too few
 * comparables fall back to the global median (also clamped).
 */
export function categoryMultiples(
  snapshot: Snapshot,
  model: ModelConstants = MODEL,
): Record<string, { multiple: number; comparables: number }> {
  const byCat = new Map<string, number[]>();
  for (const p of snapshot.protocols) {
    // A $0 market cap is a dead or unpriced token, not a market price:
    // 15 protocols in this snapshot record mcap_usd 0. They are excluded
    // from comparables (they are still token-bearing, so isPreToken
    // does not count them as pre-token).
    if (p.category === null || p.mcap_usd === null || p.mcap_usd <= 0 || p.tvl_usd <= 0) continue;
    const list = byCat.get(p.category) ?? [];
    list.push(p.mcap_usd / p.tvl_usd);
    byCat.set(p.category, list);
  }
  const out: Record<string, { multiple: number; comparables: number }> = {};
  for (const [cat, ratios] of byCat) {
    if (ratios.length >= model.min_comparables) {
      out[cat] = {
        multiple: Math.min(model.max_multiple, Math.max(model.min_multiple, median(ratios))),
        comparables: ratios.length,
      };
    }
  }
  return out;
}

export function multipleFor(
  category: string | null,
  multiples: Record<string, { multiple: number; comparables: number }>,
  model: ModelConstants = MODEL,
): { multiple: number; comparables: number } {
  if (category !== null && multiples[category] !== undefined) return multiples[category]!;
  return { multiple: model.global_multiple, comparables: 0 };
}

/** The multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
  multiples: Record<string, { multiple: number; comparables: number }>,
): {
  implied: number;
  categoryMultiple: number;
  comparablesN: number;
  growthPct: number;
  growthMult: number;
  maturityMult: number;
  chainMult: number;
  age: number | null;
} {
  const age = ageDays(asOf, protocol.listed_at);
  const { multiple: categoryMultiple, comparables: comparablesN } = multipleFor(protocol.category, multiples, model);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult =
    model.maturity_floor +
    model.maturity_range * (Math.log(1 + Math.min(Math.max(ageForModel, 0), model.maturity_days)) / Math.log(1 + model.maturity_days));
  const extraChains = Math.min(Math.max(protocol.chains.length - 1, 0), model.max_chain_bonus_chains);
  const chainMult = 1 + model.chain_bonus_per_chain * extraChains;
  const implied = Math.max(
    1,
    Math.round(protocol.tvl_usd * categoryMultiple * model.launch_discount * growthMult * maturityMult * chainMult),
  );
  return { implied, categoryMultiple, comparablesN, growthPct, growthMult, maturityMult, chainMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/** Whether a protocol is one the board may rank: pre-token, not an exchange, not a versioned pool. */
export function isRankable(p: SnapshotProtocol): boolean {
  return isPreToken(p) && p.category !== 'CEX' && !VERSIONED.test(p.name);
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

